"""Capture the installed cloud runtime dependency closure; exclude local dev tools."""
from importlib.metadata import distribution
from pathlib import Path
from packaging.requirements import Requirement

pending = ['fastapi', 'uvicorn', 'python-dotenv', 'tzdata', 'google-cloud-storage']
resolved = {}
while pending:
    name = pending.pop()
    dist = distribution(name)
    canonical = dist.metadata['Name'].lower().replace('_', '-')
    if canonical in resolved:
        continue
    resolved[canonical] = dist.version
    for raw in dist.requires or []:
        req = Requirement(raw)
        if req.marker is None or req.marker.evaluate({'extra': ''}):
            pending.append(req.name)
target = Path(__file__).resolve().parents[1] / 'backend/requirements/cloud.lock'
target.write_text('# Pinned cloud runtime dependencies; generated by infrastructure/Lock-Cloud-Dependencies.py\n'
                  + ''.join(f'{name}=={version}\n' for name, version in sorted(resolved.items())), encoding='utf-8')
print(f'Locked {len(resolved)} runtime packages to {target.name}')
